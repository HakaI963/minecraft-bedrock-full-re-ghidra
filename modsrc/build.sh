#!/bin/bash
# Self-contained build for the BlueCube native-only LeviLauncher mod.
set -e
cd /home/flux/final_mod
NDK=/home/flux/ndk/android-ndk-r28c
CLANG=$NDK/toolchains/llvm/prebuilt/linux-x86_64/bin/clang++
SYS=$NDK/toolchains/llvm/prebuilt/linux-x86_64/sysroot
SDK=/home/flux/LeviLauncher-Android/app/src/main/cpp/preloader/include
INC=src/include
SH=/home/flux/shadowhook/shadowhook/src/main/cpp/include

# FinalMod.h is a clean declaration-only header; main.cpp includes FinalMod.cpp
# for the full implementation. No header regeneration needed.

# ---- Build fingerprint: uniquely identify this source revision -------------
# Hash the implementation sources (NOT the generated build_id.h) so the ID is a
# stable function of the code. Embedded into the .so and printed at init.
SRC_FILES="src/FinalMod.cpp src/FinalMod.h src/main.cpp src/offsets.h src/creative_inventory_api/CreativeInventoryAPI.cpp"
SRC_HASH=$(cat $SRC_FILES | sha256sum | cut -c1-16)
BUILD_ID="BC100-${SRC_HASH}"
printf '// GENERATED by build.sh — do not edit. Source-revision fingerprint.\n#define BLUECUBE_BUILD_ID "%s"\n' "$BUILD_ID" > src/build_id.h
echo "build fingerprint: $BUILD_ID"

qemu-x86_64 "$CLANG" --target=aarch64-linux-android24 --sysroot="$SYS" \
  -I"$SDK" -I"$INC" -std=c++20 -O2 -fPIC \
  -c src/creative_inventory_api/CreativeInventoryAPI.cpp -o .final_build/ci_api.o

qemu-x86_64 "$CLANG" --target=aarch64-linux-android24 --sysroot="$SYS" \
  -I"$SDK" -I"$INC" -I"$SH" -I/home/flux/fmt/include -Isrc \
  -DFMT_HEADER_ONLY=1 -std=c++20 -O1 -fPIC \
  -c src/main.cpp -o .final_build/main.o

qemu-x86_64 "$CLANG" --target=aarch64-linux-android24 --sysroot="$SYS" \
  -shared -Wl,-Bsymbolic -o .final_build/libfinal_mod.so \
  .final_build/main.o .final_build/ci_api.o /tmp/sh_build/libshadowhook.a /tmp/sh_glue.o \
  -L"$SYS/usr/lib/aarch64-linux-android/24" \
  -llog -ldl -Wl,--unresolved-symbols=ignore-all

echo "built libfinal_mod.so ($(stat -c%s .final_build/libfinal_mod.so) bytes)"

cp .final_build/libfinal_mod.so libfinal_mod.so

# ---- Build report + package metadata: map source fingerprint -> binary hash -
SO_SHA=$(sha256sum libfinal_mod.so | cut -d' ' -f1)
{
  echo "build_fingerprint=$BUILD_ID"
  echo "so_sha256=$SO_SHA"
  echo "source_files=$SRC_FILES"
  echo "built_utc=$(date -u +%Y-%m-%dT%H:%M:%SZ)"
} > BUILD_ID.txt
{
  echo "# BlueCube build report"
  echo "- Build fingerprint (embedded in .so, printed at init): \`$BUILD_ID\`"
  echo "- Packaged native library SHA-256: \`$SO_SHA\`"
  echo "- Built (UTC): $(date -u +%Y-%m-%dT%H:%M:%SZ)"
  echo "- Source files hashed: $SRC_FILES"
} > BUILD_REPORT.md
echo "so sha256: $SO_SHA"
